def build():
    """STEPS → 엔진 사건 목록. act 는 각 장의 첫 단계에 붙여, 이후 단계에도 이어 붙인다."""
    out, n, act = [], 0, ""
    for item in STEPS:
        if isinstance(item, tuple):
            act, *evs = item
        else:
            evs = [item]
        n += 1
        for ev in evs:
            ev = dict(ev, k=float(n), lab=str(n), act=act)
            out.append(ev)
    return out, n


