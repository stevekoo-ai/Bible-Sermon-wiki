def apply_fine_judah(events):
    used = set()
    for e in events:
        for pre, spec in FINE_JUDAH.items():
            if e["title"].startswith(pre):
                e["fine_at"] = spec["at"]
                if "route" in spec:
                    e["fine_route"] = spec["route"]
                    e["fine_mode"] = spec.get("mode", "tail")
                used.add(pre)
    miss = set(FINE_JUDAH) - used
    assert not miss, miss
    return events


def apply_fine_genealogy(events):
    seen = set()
    for e in events:
        n = int(e["k"]) if float(e["k"]).is_integer() else None
        where = e["where"] if isinstance(e["where"], list) else [e["where"]]
        if n in FINE_NUM and where[-1] == "예루살렘" and n not in seen:
            e["fine_at"] = FINE_NUM[n]
            seen.add(n)
    miss = set(FINE_NUM) - seen
    assert not miss, miss
    return events
