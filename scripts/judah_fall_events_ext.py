def build_events():
    by_lab = {}
    for e in OLD:
        by_lab.setdefault(int(e["lab"]), []).append(e)
    out, n = [], 0
    used = set()
    for item in ORDER:
        n += 1
        if isinstance(item, int):
            used.add(item)
            for e in by_lab[item]:
                out.append(dict(e, k=float(n), lab=str(n)))
        else:
            out.append(dict(item, k=float(n), lab=str(n)))
    miss = set(by_lab) - used
    assert not miss, miss
    return out, n
